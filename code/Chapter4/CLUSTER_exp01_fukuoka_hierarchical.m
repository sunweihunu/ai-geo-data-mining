%% 案例1：福冈甜橘引种地点的层次聚类（多函数法）
% 对应书稿 4.6.1 节（表 4-18、表 4-19）
% 数据：福冈与 6 个候选城市 × 5 个气象指标（福冈/合肥/成都三行据课件，
%       其余为按气候常年值整理的示例值，与 data/fukuoka_climate.csv 一致）
clear; clc;

% 1. 数据：年平均气温(℃)、年降水量(mm)、年日照时数(h)、极端最低气温(℃)、一月平均气温(℃)
X    = [16.2 1492 2000  -8.2 6.2;    % 福冈
       15.7  970 2209 -20.6 1.9;    % 合肥
       16.9 1250 1950 -18.1 3.9;    % 武汉
       17.2 1400 1650 -11.5 4.8;    % 长沙
       18.9 1900 1550  -4.9 8.0;    % 桂林
       17.9 1720 1750  -4.5 7.7;    % 温州
       16.3  976 1239  -4.6 5.6];   % 成都
city = {'福冈','合肥','武汉','长沙','桂林','温州','成都'};

% 2. 课件方案 1：中心法 + 标准欧氏距离（标准化消除量纲差异）
D  = pdist(X, 'seuclidean');        % 计算样品之间的标准化欧氏距离
Z1 = linkage(D, 'centroid');        % 中心法聚类
figure; dendrogram(Z1, 'Labels', city);
title('引种案例谱系图：中心法 + 标准欧氏距离'); ylabel('合并高度（标准化距离）');
C1 = cophenet(Z1, D)                % Cophenetic 相关系数：越接近 1 越好

% 3. 课件方案 2：最短距离法 + 基于主成分的标准欧氏距离
coeff = pca(X);                     % 主成分变换（消除变量相关性）
score = X * coeff;                  % 主成分得分
D2 = pdist(score(:, 1:2), 'seuclidean');   % 取前两个主成分算距离
Z2 = linkage(D2, 'single');         % 最短距离法聚类
figure; dendrogram(Z2, 'Labels', city);
title('引种案例谱系图：最短距离法 + 基于主成分的距离');

% 4. 与福冈的距离排序：哪个城市最接近？
sd  = std(X);                       % 各指标标准差
d0  = sqrt(sum(((X - X(1,:)) ./ sd).^2, 2));   % 各城市到福冈的标准化欧氏距离
[~, order] = sort(d0);
fprintf('与福冈由近到远：');
fprintf('%s(%.2f) ', city{order}); fprintf('\n');

% 5. 切成 3 类并输出每个城市属于哪一类（用户友好的结果输出）
T = cluster(Z1, 'maxclust', 3);
for k = 1:3
    fprintf('第 %d 类: %s\n', k, strjoin(city(T == k), ', '));
end
