%% 创建网络。
% 用于函数拟合（或回归）问题的默认网络 
[inputs,targets] = cancer_dataset;

% patternnet 是一个前馈网络，其默认 tan-sigmoid 传递函数在隐藏层，softmax 传递函数在输出层。
% 首先，您（人为地选择）将十个神经元分配给一个隐藏层。
% 网络有两个输出神经元，因为有两个目标值（类别）与每个输入向量关联。每个输出神经元表示一个类别。
% 将相应类别的输入向量应用于网络时，对应的神经元应生成 1，其他神经元应输出 0。
% 要创建网络，请输入以下命令：

hiddenLayerSize = 10;
net = patternnet(hiddenLayerSize);
% 注意：模式识别问题的网络架构选择所遵循的规范与函数拟合问题类似。
% 神经元越多，需要的计算也越多；当数量设置得太高时，可能会出现数据过拟合倾向，
% 但这使网络能够求解更复杂的问题。层越多，需要的计算也越多，
% 但使用更多的层可以使网络更高效地求解复杂问题。
% 要使用多个隐藏层，请在 patternnet 命令中输入隐藏层大小作为数组的元素。

% 设置数据划分。

net.divideParam.trainRatio = 70/100;
net.divideParam.valRatio   = 15/100;
net.divideParam.testRatio  = 15/100;

% 基于以上设置，输入向量和目标向量都将被随机划分为三组，
% 其中 70% 用于训练，15% 用于验证，15% 用于测试。
% （有关数据划分流程的更多讨论，请参阅划分数据。）
% 训练网络。模式识别网络使用默认的量化共轭梯度 (trainscg) 算法进行训练。
% 要训练网络，请输入以下命令：

[net,tr] = train(net,inputs,targets);
% 在训练过程中，与函数拟合时一样，训练窗口将打开。
% 此窗口显示训练进度。要随时中断训练，请点击 Stop Training。

% 如果验证误差在六次迭代中持续增加，则训练将在第 24 次迭代时停止。
% 测试网络。您可以使用经过训练的网络来计算网络输出。以下代码将计算网络输出、误差和整体性能。

outputs = net(inputs);
errors = gsubtract(targets,outputs);
performance = perform(net,targets,outputs)  % performance =    0.0307

% 通过使用训练记录中的测试索引，还可以只针对测试集计算网络性能。

tInd = tr.testInd;
tstOutputs = net(inputs(:,tInd));
tstPerform = perform(net,targets(:,tInd),tstOutputs)  % tstPerform =    0.0257

% 查看网络图。
view(net)
% 绘制训练、验证和测试性能图。
figure, plotperform(tr)
% 使用 plotconfusion 函数绘制混淆矩阵。它显示最终经过训练的网络发生的各种类型的误差。
figure, plotconfusion(targets,outputs)

