% 有三个非常靠近上方簇中用正方形表示的点。由于上方簇相当分散，
% 这三个点更靠近下方簇的质心而不是上方簇的质心，
% 虽然这些点与所在簇中的大部分点存在明显距离。
% 由于 K 均值聚类只考虑距离而不是密度，因此可能会出现这种结果。




