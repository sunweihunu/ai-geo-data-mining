
% Fisher 鸢尾花数据
% 20 世纪 20 年代，植物学家收集了 150 个鸢尾花标本（三个品种各取 50 个标本）的
% 萼片长度、萼片宽度、花瓣长度和花瓣宽度的测量值。这些测量值被称为 Fisher 鸢尾花数据集。
% 
% 在此数据集中，每个观测值都来自一个已知的品种，因此已经有明显的方法对数据进行分组。
% 现在，我们将忽略品种信息，仅使用原始测量值对数据进行聚类。
% 完成后，我们可以将得到的簇与实际的品种进行比较，以了解这三种鸢尾花是否具有不同的特性。

% 使用 K 均值聚类方法对 Fisher 鸢尾花数据进行聚类
% 函数 kmeans 使用迭代算法执行 K 均值聚类，该算法将对象分配给簇，
% 使每个对象到其所在簇质心的距离之和最小。对 Fisher 鸢尾花数据应用该函数时，
% 它将根据鸢尾花标本萼片和花瓣的测量值找到它们的自然分组。
% 使用 K 均值聚类，您必须指定要创建的簇数。

% ========== Step 0 设定随机数
% 将随机数生成器设置为已知状态。
rng(6,'twister')


% Clustering Fisher's Iris Data Using K-Means Clustering
% 加载数据并调用 kmeans，将所需的簇数设置为 2，并使用平方欧几里德距离。
% ========== Step 1 加载数据并 k-means聚类
load fisheriris
[cidx2,cmeans2] = kmeans(meas,2,'dist','sqeuclidean');

% ========== Step 2 绘制轮廓图
% 要了解生成的簇区分数据的效果，可以绘制轮廓图。
% 轮廓图显示一个簇中的每个点与相邻簇中的点的接近程度。
figure;
[silh2,h] = silhouette(meas,cidx2,'sqeuclidean');
title('2簇的k-means聚类的轮廓图');

% 从轮廓图中可以看出，两个簇中的大多数点都具有较大的轮廓值（大于 0.8），
% 表明这些点可以与相邻簇很好地区分。但是，每个簇中还有一些点的轮廓值较低，
% 表示它们靠近其他簇中的点。
% 

% ========== Step 3 绘制基于前三个维度的散点图
% 事实证明，这些数据中的第四个测量值（花瓣宽度）与第三个测量值（花瓣长度）高度相关，
% 因此前三个测量值的三维图可以很好地表示数据，而无需求助于四个维度。如果绘制数据，
% 则使用不同的符号表示 kmeans 创建的每个簇，
% 就可以识别轮廓值较小的点，也就是与其他簇中的点相距较近的点。

figure;
ptsymb = {'bs','r^','md','go','c+'};
for i = 1:2
    clust = find(cidx2==i);
    plot3(meas(clust,1),meas(clust,2),meas(clust,3),ptsymb{i});
    hold on
end
plot3(cmeans2(:,1),cmeans2(:,2),cmeans2(:,3),'ko');
plot3(cmeans2(:,1),cmeans2(:,2),cmeans2(:,3),'kx');
hold off
xlabel('Sepal Length');
ylabel('Sepal Width');
zlabel('Petal Length');
view(-137,10);
grid on
title ('基于前三个维度的2簇的散点图');

