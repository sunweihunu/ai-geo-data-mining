%层次聚类分析
%最长距离法&欧式距离
% cityname=['福岗';'合肥';'武汉';'长沙';'桂林';'温州';'成都'];
cityname={'福岗';'合肥';'武汉';'长沙';'桂林';'温州';'成都'};
X=[16.2  1492  2000  -8.2  6.2
15.7  970   2209  -20.6  1.9
16.3  1260  2085  -17.3  2.8
17.2  1422  1726  -9.5   4.6
18.8  1874  1709  -4.9   8.0
17.9  1698  1848  -4.5   7.5
16.3  976   1239  -4.6   5.6];      
%数据标准化，即减去均值，然后除以标准差
X = zscore(X);

%K均值聚类分析，分3类，也可以人为指定初始凝聚点
idx=kmeans(X,3);

% 绘制轮廓图 ，并返回轮廓值向量S和图形句柄H
[S, H] = silhouette(X,idx);

%查看聚类结果
disp('No 1')
cityname{find(idx==1)}  %查看第1类所包含的地区
disp('No 2')
cityname{find(idx==2)} %查看第2类所包含的地区
disp('No 3')
cityname{find(idx==3)}  %查看第3类所包含的地区
